# Builds GatherData.lua for ReadyToWork's Gathering skill helper (not loaded by the game).
# Put these next to this script in a folder named cmdb, then run: python gatherdata.py ..\GatherData.lua
#   cmdb/db.sql.gz  https://raw.githubusercontent.com/cmangos/classic-db/master/Full_DB/ClassicDB_1_12_1_z2815.sql.gz
#   cmdb/lock.csv   https://wago.tools/db2/Lock/csv?branch=wow_classic_era
#   cmdb/area.csv   https://wago.tools/db2/AreaTable/csv?branch=wow_classic_era
import gzip, csv, collections, os, sys
base = os.path.dirname(os.path.abspath(__file__))

def rows(line):
    body = line[line.index('VALUES') + 6:].strip().rstrip(';')
    out, cur, field, inq, esc, depth = [], [], '', False, False, 0
    for ch in body:
        if inq:
            if esc: field += ch; esc = False
            elif ch == '\\': esc = True
            elif ch == "'": inq = False
            else: field += ch
            continue
        if ch == "'": inq = True
        elif ch == '(':
            depth += 1; cur = []; field = ''
        elif ch == ')':
            cur.append(field); out.append(cur); depth -= 1; field = ''
        elif ch == ',' and depth == 1:
            cur.append(field); field = ''
        elif depth == 1: field += ch
    return out

tmpl, spawns, fishbase = {}, collections.Counter(), {}
with gzip.open(os.path.join(base, 'cmdb', 'db.sql.gz'), 'rt', encoding='utf-8', errors='replace') as db:
    for line in db:
        if line.startswith('INSERT INTO `gameobject_template`'):
            for r in rows(line): tmpl[int(r[0])] = r
        elif line.startswith('INSERT INTO `gameobject` '):
            for r in rows(line): spawns[int(r[1])] += 1
        elif line.startswith('INSERT INTO `gameobject_spawn_entry`'):
            for r in rows(line): spawns[int(r[1])] += 1
        elif line.startswith('INSERT INTO `skill_fishing_base_level`'):
            for r in rows(line): fishbase[int(r[0])] = int(r[1])

locks = {}
for r in csv.DictReader(open(os.path.join(base, 'cmdb', 'lock.csv'), encoding='utf-8')):
    req = {}
    for i in range(8):
        if r['Type_%d' % i] == '2':
            req[int(r['_Index_%d' % i])] = int(r['Skill_%d' % i])
    locks[int(r['ID'])] = req

KIND = {1: 'lock', 2: 'herb', 3: 'mine'}
names = collections.defaultdict(lambda: collections.defaultdict(set))
ids = {}
pools = set()
for entry, r in tmpl.items():
    typ, name = int(r[1]), r[3]
    if typ == 25:
        if spawns[entry]: pools.add(name)
        continue
    if typ != 3: continue
    req = locks.get(int(r[8])) or {}
    for idx, skill in req.items():
        k = KIND.get(idx)
        if not k or 'Point Check' in name or 'should not' in name: continue
        if k == 'lock' and not spawns[entry]: continue
        skill = max(skill, 1)
        names[k][name].add(skill)
        ids[entry] = (k, skill)

area = {}
for r in csv.DictReader(open(os.path.join(base, 'cmdb', 'area.csv'), encoding='utf-8')):
    area[int(r['ID'])] = (r['AreaName_lang'], int(r['ParentAreaID']))

zones, subzones = {}, {}
for aid, skill in sorted(fishbase.items()):
    if aid not in area: continue
    nm, parent = area[aid]
    if parent == 0:
        zones[nm] = skill
    else:
        pname = area.get(parent, ('', 0))[0]
        subzones[pname + '\t' + nm] = skill

def q(s): return '"' + s.replace('\\', '\\\\').replace('"', '\\"').replace('\t', '\\t') + '"'
def rng(v): v = sorted(v); return '%d' % v[0] if len(v) == 1 else '{%s}' % ', '.join(map(str, v))

out = []
w = out.append
w('-- Generated by Tools/gatherdata.py from the CMaNGOS Classic database (classic-db')
w('-- ClassicDB_1_12_1_z2815: gameobject_template, spawns, skill_fishing_base_level)')
w('-- and the game\'s Lock and AreaTable tables for Classic Era (wago.tools).')
w('-- Do not edit by hand: regenerate. A number is the skill needed; a list means')
w('-- objects of that name come with different locks.')
w('local _, Helper = ...')
w('Helper.GatherData = {')
for k, label in (('herb', 'herbs'), ('mine', 'mine'), ('lock', 'lock')):
    w('\t%s = {' % label)
    d = names[k]
    for n in sorted(d, key=lambda n: (min(d[n]), n)):
        w('\t\t[%s] = %s,' % (q(n), rng(d[n])))
    w('\t},')
w('\tlockIDs = {')
for e in sorted(x for x in ids if ids[x][0] == 'lock'):
    w('\t\t[%d] = %d,' % (e, ids[e][1]))
w('\t},')
w('\tpools = {')
for n in sorted(pools): w('\t\t[%s] = true,' % q(n))
w('\t},')
w('\tfishZones = {')
for n in sorted(zones): w('\t\t[%s] = %d,' % (q(n), zones[n]))
w('\t},')
w('\tfishSubzones = {')
for n in sorted(subzones): w('\t\t[%s] = %d,' % (q(n), subzones[n]))
w('\t},')
w('}')
open(sys.argv[1], 'w', encoding='utf-8', newline='\n').write('\n'.join(out) + '\n')
print('herbs', len(names['herb']), 'mine', len(names['mine']), 'lock', len(names['lock']), 'lockIDs', sum(1 for x in ids if ids[x][0]=='lock'), 'pools', len(pools), 'zones', len(zones), 'subzones', len(subzones), 'fishbase', len(fishbase))
print(sorted(pools))
print({n: sorted(v) for n, v in names['mine'].items()})
